// Deploys OrganizerRegistry + ChallengeFactory (+ optional mock tokens) and writes frontend/js/config.js
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

async function main() {
  const { ethers, network } = hre;
  const env = process.env;
  const [deployer] = await ethers.getSigners();
  const chainId = Number((await ethers.provider.getNetwork()).chainId);
  console.log(`Network ${network.name} (chain ${chainId}) | deployer ${deployer.address}`);

  const arbiter = env.ARBITER_ADDRESS || deployer.address;
  if (arbiter === deployer.address) console.warn("WARNING: arbiter == deployer. Use an independent multisig in production.");

  const tokens = [{ symbol: env.NATIVE_SYMBOL || "NATIVE", address: ethers.ZeroAddress, decimals: 18 }];
  let bot = env.BOT_TOKEN_ADDRESS, usdt = env.USDT_TOKEN_ADDRESS;

  if (env.DEPLOY_MOCKS === "true") {
    const Mock = await ethers.getContractFactory("MockToken");
    const b = await Mock.deploy("Bot Token", "BOT", 18); await b.waitForDeployment();
    const u = await Mock.deploy("Tether USD (mock)", "USDT", 6); await u.waitForDeployment();
    bot = await b.getAddress(); usdt = await u.getAddress();
    console.log("Mock BOT:", bot, "\nMock USDT:", usdt);
  }

  const Registry = await ethers.getContractFactory("OrganizerRegistry");
  const registry = await Registry.deploy(); await registry.waitForDeployment();

  const Factory = await ethers.getContractFactory("ChallengeFactory");
  const factory = await Factory.deploy(await registry.getAddress(), arbiter); await factory.waitForDeployment();

  if (bot)  { await (await factory.setTokenAllowed(bot, true)).wait();  tokens.push({ symbol: "BOT",  address: bot,  decimals: 18 }); }
  if (usdt) { await (await factory.setTokenAllowed(usdt, true)).wait(); tokens.push({ symbol: "USDT", address: usdt, decimals: 6 }); }

  const out = {
    chainId,
    chainName: env.CHAIN_NAME || network.name,
    rpcUrl: env.RPC_URL || "http://127.0.0.1:8545",
    explorer: env.EXPLORER_URL || "",
    registry: await registry.getAddress(),
    factory: await factory.getAddress(),
    arbiter,
    tokens,
  };

  fs.mkdirSync(path.join(__dirname, "../deployments"), { recursive: true });
  fs.writeFileSync(path.join(__dirname, `../deployments/${network.name}.json`), JSON.stringify(out, null, 2));
  fs.writeFileSync(
    path.join(__dirname, "../frontend/js/config.js"),
    `// Generated by scripts/deploy.js\nwindow.CODEARENA_CONFIG = ${JSON.stringify(out, null, 2)};\n`
  );
  console.log(out);
}

main().catch((e) => { console.error(e); process.exit(1); });
